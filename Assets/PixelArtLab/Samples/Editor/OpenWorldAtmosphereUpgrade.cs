        const string Art="Assets/Art/Atmosphere";
        public static void VerifyRepeatable()
        {
            var before=AssetDatabase.LoadAssetAtPath<Mesh>(Art+"/FlexibleFlag.asset");int count=before?before.vertexCount:0;
            Apply();
            var after=AssetDatabase.LoadAssetAtPath<Mesh>(Art+"/FlexibleFlag.asset");
            if(!after||after.vertexCount>40000||(count>0&&after.vertexCount!=count))throw new System.Exception("Flag geometry grew during repeated application");
            File.WriteAllText("Previews/Atmosphere-Authoring-Verification.txt","REPEATABLE_ATMOSPHERE_UPGRADE_SUCCESS\nFlag vertex count: "+after.vertexCount+"\nNo recursive subdivision\nNO PLAYER BUILD WAS RUN\n");
        }
        [MenuItem("Pixel Art Lab/Apply Day Night and Weather to Free Roam")]
        public static void Apply()
        {
            Directory.CreateDirectory(Art);
            EditorSceneManager.OpenScene(OpenWorldSceneBuilder.ScenePath);
            var player=Object.FindFirstObjectByType<ExplorerMotor>();var follow=Object.FindFirstObjectByType<ExplorationCamera>();
            var env=Object.FindFirstObjectByType<WorldEnvironment>();if(!env)env=new GameObject("Valley Time Weather and Wind").AddComponent<WorldEnvironment>();
            env.sun=RenderSettings.sun;env.worldCamera=follow.GetComponent<Camera>();env.player=player;
            env.torches=Object.FindObjectsByType<Light>(FindObjectsSortMode.None).Where(l=>l.type==LightType.Point).ToArray();
            var root=GameObject.Find("Amberwood — 150m Seamless Exploration Map").transform;
            foreach(Transform item in root)
            {
                string name=item.name;WorldMotionKind mode=WorldMotionKind.None;
                if(name.StartsWith("tree_"))mode=WorldMotionKind.Tree;
                if(name.StartsWith("grass")||name.StartsWith("plant_")||name.StartsWith("flower_"))mode=WorldMotionKind.Grass;
                if(name=="flag")mode=WorldMotionKind.Flag;
                if(name=="Stillwater Lake"&&item.GetComponent<MeshFilter>())mode=WorldMotionKind.Water;
                if(mode==WorldMotionKind.None)continue;
                if(mode==WorldMotionKind.Water){ReplaceLake(item.gameObject);foreach(var m in item.GetComponent<MeshRenderer>().sharedMaterials){m.SetFloat("_WaterSurface",1);SpriteToonKeywords.Sync(m);EditorUtility.SetDirty(m);}}
                if(mode==WorldMotionKind.Flag)SubdivideFlag(item.gameObject);
                var motion=item.GetComponent<WorldSurfaceMotion>();if(!motion)motion=item.gameObject.AddComponent<WorldSurfaceMotion>();motion.kind=mode;motion.Apply();if(mode==WorldMotionKind.Water)ComponentMigration.AddLake(item.gameObject);
            }
            var alignment=player.GetComponent<PixelCharacterAlignment>();if(!alignment)alignment=player.gameObject.AddComponent<PixelCharacterAlignment>();alignment.player=player;alignment.follow=follow;
            player.steppedFacing=true;
            var particle=Object.FindFirstObjectByType<PixelWeatherParticles>();if(!particle)particle=new GameObject("Pixel Rain Snow and Ground Splashes").AddComponent<PixelWeatherParticles>();
            particle.environment=env.State;
            string path=Art+"/Precipitation.mat";var material=AssetDatabase.LoadAssetAtPath<Material>(path);
            if(!material){material=new Material(Shader.Find("PixelArtLab/Weather Particles"));AssetDatabase.CreateAsset(material,path);}
            particle.weatherMaterial=material;particle.GetComponent<MeshRenderer>().sharedMaterial=material;
            Object.FindFirstObjectByType<ExplorationWorld>().environment=env;
            env.hour=14;env.runClock=true;env.animationTime=0;env.SetWeather(WeatherKind.Clear,true);
            AssetDatabase.SaveAssets();EditorSceneManager.SaveScene(UnityEngine.SceneManagement.SceneManager.GetActiveScene(),OpenWorldSceneBuilder.ScenePath);
            // Remove only superseded files generated by this upgrade, after the scene uses the stable asset.
            AssetDatabase.DeleteAsset(Art+"/Flag-flag.asset");
            AssetDatabase.DeleteAsset(Art+"/Flag-Flag-flag.asset");
            PreviewStates(env,particle);
            Debug.Log("ATMOSPHERE_SCENE_SUCCESS motionObjects="+Object.FindObjectsByType<WorldSurfaceMotion>(FindObjectsSortMode.None).Length);
        }
        static void ReplaceLake(GameObject lake)
        {
            const int rings=24,sectors=96;
            var vertices=new List<Vector3>{Vector3.zero};var normals=new List<Vector3>{Vector3.up};var uv=new List<Vector2>{new Vector2(.5f,.5f)};var triangles=new List<int>();
            for(int ring=1;ring<=rings;ring++)for(int i=0;i<sectors;i++)
            {
                float a=i*Mathf.PI*2/sectors,r=(float)ring/rings*.5f;var p=new Vector3(Mathf.Cos(a)*r,0,Mathf.Sin(a)*r);
                vertices.Add(p);normals.Add(Vector3.up);uv.Add(new Vector2(p.x+.5f,p.z+.5f));
                int current=1+(ring-1)*sectors+i,next=1+(ring-1)*sectors+(i+1)%sectors;
                if(ring==1)triangles.AddRange(new[]{0,next,current});
                else {int previous=current-sectors,previousNext=next-sectors;triangles.AddRange(new[]{previous,previousNext,current,previousNext,next,current});}
            }
            var mesh=new Mesh{name="Tessellated lake surface"};mesh.SetVertices(vertices);mesh.SetNormals(normals);mesh.SetUVs(0,uv);mesh.SetTriangles(triangles,0);
            mesh.bounds=new Bounds(Vector3.zero,new Vector3(1,6,1));
            string path=Art+"/LakeSurface.asset";var existing=AssetDatabase.LoadAssetAtPath<Mesh>(path);if(existing){EditorUtility.CopySerialized(mesh,existing);Object.DestroyImmediate(mesh);mesh=existing;}else AssetDatabase.CreateAsset(mesh,path);
            lake.GetComponent<MeshFilter>().sharedMesh=mesh;
        }
        static void SubdivideFlag(GameObject flag)
        {
            foreach(var filter in flag.GetComponentsInChildren<MeshFilter>())
            {
                const string path=Art+"/FlexibleFlag.asset";var existing=AssetDatabase.LoadAssetAtPath<Mesh>(path);
                if(existing){filter.sharedMesh=existing;continue;}
                // Always subdivide the original FBX, never an already generated mesh.
                var original=AssetDatabase.LoadAssetAtPath<GameObject>("Assets/ThirdParty/KenneyCastle/flag.fbx");
                var source=original.GetComponentInChildren<MeshFilter>().sharedMesh;
                var positions=new List<Vector3>();var normals=new List<Vector3>();var uvs=new List<Vector2>();var triangles=new List<int>();
                var v=source.vertices;var n=source.normals;var uv=source.uv;
                foreach(var sub in Enumerable.Range(0,source.subMeshCount))
                {
                    var indices=source.GetTriangles(sub);
                    for(int i=0;i<indices.Length;i+=3)
                    {
                        int a=indices[i],b=indices[i+1],c=indices[i+2];Split(v[a],v[b],v[c],n[a],n[b],n[c],uv[a],uv[b],uv[c],3,positions,normals,uvs,triangles);
                    }
                }
                var mesh=new Mesh{name="Flexible flag cloth"};mesh.SetVertices(positions);mesh.SetNormals(normals);mesh.SetUVs(0,uvs);mesh.SetTriangles(triangles,0);mesh.RecalculateBounds();
                // Imported flag uses a single color-atlas material.
                AssetDatabase.CreateAsset(mesh,path);filter.sharedMesh=mesh;
            }
        }
        static void Split(Vector3 a,Vector3 b,Vector3 c,Vector3 na,Vector3 nb,Vector3 nc,Vector2 ua,Vector2 ub,Vector2 uc,int level,List<Vector3> vertices,List<Vector3> normals,List<Vector2> uv,List<int> triangles)
        {
            if(level==0){int i=vertices.Count;vertices.AddRange(new[]{a,b,c});normals.AddRange(new[]{na,nb,nc});uv.AddRange(new[]{ua,ub,uc});triangles.AddRange(new[]{i,i+1,i+2});return;}
            var ab=(a+b)*.5f;var bc=(b+c)*.5f;var ca=(c+a)*.5f;var nab=(na+nb).normalized;var nbc=(nb+nc).normalized;var nca=(nc+na).normalized;var uab=(ua+ub)*.5f;var ubc=(ub+uc)*.5f;var uca=(uc+ua)*.5f;
            Split(a,ab,ca,na,nab,nca,ua,uab,uca,level-1,vertices,normals,uv,triangles);Split(ab,b,bc,nab,nb,nbc,uab,ub,ubc,level-1,vertices,normals,uv,triangles);Split(ca,bc,c,nca,nbc,nc,uca,ubc,uc,level-1,vertices,normals,uv,triangles);Split(ab,bc,ca,nab,nbc,nca,uab,ubc,uca,level-1,vertices,normals,uv,triangles);
        }
        static void PreviewStates(WorldEnvironment env,PixelWeatherParticles particles)
        {
            var camera=env.worldCamera;var position=camera.transform.position;var rotation=camera.transform.rotation;float size=camera.orthographicSize;
            env.runClock=false;env.hour=13;env.animationTime=2;env.SetWeather(WeatherKind.Clear,true);particles.Refresh(true);OpenWorldSceneBuilder.Capture(camera,"Previews/16-Weather-Day.png");
            env.hour=17.5f;env.Apply();particles.Refresh(true);OpenWorldSceneBuilder.Capture(camera,"Previews/24-Weather-Sunset.png");
            env.hour=0;env.Apply();particles.Refresh(true);OpenWorldSceneBuilder.Capture(camera,"Previews/17-Weather-Night.png");
            env.hour=16;env.SetWeather(WeatherKind.Rain,true);particles.Refresh(true);OpenWorldSceneBuilder.Capture(camera,"Previews/18-Weather-Rain.png");
            env.hour=11;env.SetWeather(WeatherKind.Snow,true);particles.Refresh(true);OpenWorldSceneBuilder.Capture(camera,"Previews/19-Weather-Snow.png");
            env.SetWeather(WeatherKind.Clear,true);env.hour=14;camera.transform.position=new Vector3(-30,2,22)-camera.transform.forward*45;env.animationTime=1;env.Apply();particles.Refresh(true);OpenWorldSceneBuilder.Capture(camera,"Previews/20-Lake-Motion-A.png");
            env.animationTime=3;env.Apply();particles.Refresh(true);OpenWorldSceneBuilder.Capture(camera,"Previews/21-Lake-Motion-B.png");
            camera.transform.SetPositionAndRotation(position,rotation);camera.orthographicSize=size;env.hour=14;env.animationTime=0;env.runClock=true;env.SetWeather(WeatherKind.Clear,true);particles.Refresh(true);
            EditorSceneManager.SaveScene(UnityEngine.SceneManagement.SceneManager.GetActiveScene(),OpenWorldSceneBuilder.ScenePath);
        }
